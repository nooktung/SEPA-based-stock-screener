const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const context=vm.createContext({window:{},Intl,Date});
vm.runInContext(fs.readFileSync('src/web/static/news-dates.js','utf8'),context);
const {dayKey,matches,monthCells,choose}=context.window.NewsDates;
assert.equal(dayKey('2026-10-21T17:00:00Z'),'2026-10-22');
assert.equal(dayKey('2026-10-22T00:30:00+07:00'),'2026-10-22');
assert.equal(dayKey('bad'), '');
assert.equal(matches(null,{}),true);
assert.equal(matches(null,{start:'2026-10-22',end:'2026-10-22'}),false);
const one={start:'2026-10-22',end:'2026-10-22'};
assert.ok(matches('2026-10-22T23:59:59+07:00',one));
assert.ok(matches('2026-10-21T17:00:00Z',one));
assert.ok(!matches('2026-10-22T17:00:00Z',one));
const range={start:'2026-10-19',end:'2026-10-22'};
for(const day of ['19','20','21','22']) assert.ok(matches(`2026-10-${day}T12:00:00+07:00`,range));
assert.ok(!matches('2026-10-23T00:00:00+07:00',range));
let selection=choose({mode:'range',start:'',end:''},'2026-10-22');
assert.equal(selection.end,'');
selection=choose(selection,'2026-10-19');
assert.equal(selection.start,'2026-10-19');assert.equal(selection.end,'2026-10-22');
selection=choose(selection,'2026-10-20');assert.equal(selection.start,'2026-10-20');assert.equal(selection.end,'');
selection=choose({mode:'single'},'2026-10-21');assert.equal(selection.start,selection.end);
const oct=monthCells(2026,9);assert.equal(oct.length,42);assert.equal(oct[0],'2026-09-28');
assert.equal(monthCells(2024,1).filter(x=>x.startsWith('2024-02-')).length,29);
assert.ok(monthCells(2026,0).includes('2025-12-29'));
assert.equal(new Date(oct[0]+'T00:00:00Z').getUTCDay(),1);
console.log('News date filtering and calendar tests passed');
