const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('src/web/static/app.js', 'utf8');
const start = source.indexOf('function newsPageData(');
const end = source.indexOf('function renderNewsPager(', start);
const context = vm.createContext({ NEWS_PAGE_SIZE: 15 });
vm.runInContext(source.slice(start, end), context);
const rows = Array.from({length: 31}, (_, i) => i);
const first = context.newsPageData(rows, 1);
const second = context.newsPageData(rows, 2);
const last = context.newsPageData(rows, 3);
assert.equal(first.items.length, 15);
assert.equal(second.items.length, 15);
assert.equal(last.items.length, 1);
assert.equal(last.items[0], 30);
assert.equal(new Set([...first.items, ...second.items, ...last.items]).size, 31);
assert.equal(context.newsPageData(rows, 999).page, 3);
assert.equal(context.newsPageData(rows, -5).page, 1);
assert.equal(context.newsPageData([], 3).items.length, 0);
assert.equal(context.newsPageData(rows.slice(0,15), 2).pages, 1);
assert.equal(context.newsPageData(rows.slice(0,16), 2).items.length, 1);
assert.equal(context.newsPageData(rows.slice(0,4), 3).page, 1);
console.log('News pagination: size, boundaries, stable order and filtered-page clamping passed');
